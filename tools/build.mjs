#!/usr/bin/env node
// Generates the per-host adapter files for the intel-vt skill from a single source.
//
//   node tools/build.mjs            write the adapters
//   node tools/build.mjs --check    fail if any adapter has drifted (CI)
//
// Source of truth: intel-vt/SKILL.md + intel-vt/references/*.md
// Generated:       intel-vt/index.json, intel-vt/agents/openai.yaml, AGENTS.md
//
// The content itself is never duplicated. SKILL.md is an open standard that
// Claude Code, Codex and Hermes all consume directly; these three files carry
// pointers and metadata only, so they cannot drift semantically from the prose.

import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { join, dirname, relative } from 'node:path'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SKILL = 'intel-vt'
const SKILL_DIR = join(ROOT, SKILL)
const REFS = join(SKILL_DIR, 'references')
const CHECK = process.argv.includes('--check')

const BANNER = 'DO NOT EDIT — generated by tools/build.mjs from intel-vt/SKILL.md'
const sha256 = (s) => createHash('sha256').update(s).digest('hex')

// ------------------------------------------------------------------- source

function frontmatter(text) {
  const end = text.indexOf('\n---', 4)
  const body = text.slice(4, end)
  const out = {}
  let key = null
  for (const line of body.split('\n')) {
    const m = /^([A-Za-z][A-Za-z0-9_-]*):\s?(.*)$/.exec(line)
    if (m) { key = m[1]; out[key] = m[2] === '>' || m[2] === '|' ? '' : m[2] }
    else if (key && /^\s+/.test(line)) out[key] = (out[key] + ' ' + line.trim()).trim()
  }
  return out
}

const skillText = readFileSync(join(SKILL_DIR, 'SKILL.md'), 'utf8')
const fm = frontmatter(skillText)

const chapters = readdirSync(REFS)
  .filter((f) => f.endsWith('.md'))
  .sort()
  .map((file) => {
    const text = readFileSync(join(REFS, file), 'utf8')
    const title = (/^#\s+(.+)$/m.exec(text)?.[1] ?? file).trim()
    const zh = /^>\s*\*\*中文速览\*\*[：:]\s*(.+?)$/m.exec(text)?.[1]?.trim()
    const maps = /^\*\*Maps to:\*\*\s*(.+?)$/m.exec(text)?.[1]?.replace(/\[\d+\]/g, '').trim()
    const headings = [...text.matchAll(/^##\s+(.+)$/gm)].map((m) => m[1].trim())
    return {
      path: `references/${file}`,
      title,
      summary_zh: zh ?? null,
      maps_to: maps ?? null,
      headings,
      bytes: Buffer.byteLength(text),
      sha256: sha256(text),
    }
  })

// ---------------------------------------------------------------- artifacts

const indexJson = JSON.stringify({
  $comment: BANNER,
  name: fm.name,
  description: fm.description,
  entry: 'SKILL.md',
  spec: 'https://agentskills.io/specification',
  chapters,
}, null, 2) + '\n'

const shortDesc = (fm.description ?? '').split(/(?<=[.?!])\s/)[0] ?? ''
const openaiYaml = `# ${BANNER}
interface:
  display_name: Intel VT
  short_description: ${JSON.stringify(shortDesc)}
policy:
  allow_implicit_invocation: true
`

const agentsMd = `<!-- ${BANNER} -->

# Agent instructions

## Intel virtualization knowledge base

This repository carries an Intel VT skill at \`${SKILL}/\`.

**Read \`${SKILL}/SKILL.md\` before answering anything about Intel VT-x, VMX,
VMCS, EPT, VPID, VT-d, IOMMU, APICv, posted interrupts, TDX, SEAM, nested
virtualization, or an Intel-versus-AMD/ARM/RISC-V virtualization comparison.**

It routes to one chapter under \`${SKILL}/references/\` per topic, each mapped to
the Intel specification chapter it covers. Load the chapter you need, not the
whole directory. \`${SKILL}/index.json\` is the machine-readable table of
contents.

A sibling skill at \`amd-virtualization/\` covers AMD-V/SVM/SEV. For an
AMD-primary question use that one; for an Intel-primary question or a two-way
comparison use \`${SKILL}/\`.
`

// -------------------------------------------------------------- write/check

const outputs = [
  [join(SKILL_DIR, 'index.json'), indexJson],
  [join(SKILL_DIR, 'agents', 'openai.yaml'), openaiYaml],
  [join(ROOT, 'AGENTS.md'), agentsMd],
]

let drifted = 0
for (const [path, content] of outputs) {
  const rel = relative(ROOT, path).replace(/\\/g, '/')
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null
  if (current === content) { if (!CHECK) console.log(`  unchanged  ${rel}`); continue }
  if (CHECK) {
    console.error(`  DRIFT      ${rel}${current === null ? ' (missing)' : ''}`)
    drifted++
    continue
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, content)
  console.log(`  ${current === null ? 'created   ' : 'updated   '} ${rel}`)
}

if (CHECK) {
  if (drifted) {
    console.error(`\n${drifted} generated file(s) out of date — run: node tools/build.mjs\n`)
    process.exit(1)
  }
  console.log('\ngenerated files are up to date\n')
} else {
  console.log(`\n${chapters.length} chapter(s) indexed\n`)
}
