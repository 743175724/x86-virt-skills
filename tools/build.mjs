#!/usr/bin/env node
// Generates the per-host adapter files for every skill in this repo.
//
//   node tools/build.mjs                    write the adapters for all skills
//   node tools/build.mjs intel-vt           write the adapters for one skill
//   node tools/build.mjs --check            fail if any adapter has drifted (CI)
//
// Source of truth: <skill>/SKILL.md + <skill>/references/*.md
// Generated:       <skill>/index.json, <skill>/agents/openai.yaml, AGENTS.md
//
// The content itself is never duplicated. SKILL.md is an open standard that
// Claude Code, Codex and Hermes all consume directly; these files carry
// pointers and metadata only, so they cannot drift semantically from the prose.
//
// AGENTS.md is shared by every skill, so --check always evaluates it against
// the full skill set even when a single skill was named on the command line.

import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync, statSync } from 'node:fs'
import { join, dirname, relative } from 'node:path'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const CHECK = process.argv.includes('--check')
const named = process.argv.slice(2).filter((a) => !a.startsWith('-')).map((s) => s.replace(/[\\/]+$/, ''))

// A skill is a directory holding SKILL.md. lint.config.json is required too, so
// that a half-created directory cannot silently join the build.
const allSkills = readdirSync(ROOT)
  .filter((d) => { try { return statSync(join(ROOT, d)).isDirectory() } catch { return false } })
  .filter((d) => existsSync(join(ROOT, d, 'SKILL.md')) && existsSync(join(ROOT, d, 'lint.config.json')))
  .sort()

const skills = named.length ? named : allSkills
if (!skills.length) {
  console.error('\nno skills found — a skill is a directory holding SKILL.md and lint.config.json\n')
  process.exit(1)
}

const sha256 = (s) => createHash('sha256').update(s).digest('hex')
const banner = (src) => `DO NOT EDIT — generated by tools/build.mjs from ${src}`

// ------------------------------------------------------------------- source

function frontmatter(text) {
  const end = text.indexOf('\n---', 4)
  const out = {}
  let key = null
  for (const line of text.slice(4, end).split(/\r?\n/)) {
    const m = /^([A-Za-z][A-Za-z0-9_-]*):\s?(.*)$/.exec(line)
    if (m) { key = m[1]; out[key] = m[2] === '>' || m[2] === '|' ? '' : m[2] }
    else if (key && /^\s+/.test(line)) out[key] = (out[key] + ' ' + line.trim()).trim()
  }
  return out
}

/** Everything AGENTS.md and openai.yaml need, read once per skill. */
function readSkill(name) {
  const dir = join(ROOT, name)
  const refs = join(dir, 'references')
  const text = readFileSync(join(dir, 'SKILL.md'), 'utf8')
  const fm = frontmatter(text)
  const cfg = JSON.parse(readFileSync(join(dir, 'lint.config.json'), 'utf8'))

  const desc = fm.description ?? ''
  const shortDesc = (desc.split(/(?<=[.?!])\s/)[0] ?? desc).trim()
  // A description with no terminal punctuation yields the whole block as its
  // "first sentence". Refusing beats emitting an adapter lint will reject — but
  // one malformed skill must not stop its siblings from building, so this is
  // recorded and reported at the end rather than thrown here.
  const fatal = shortDesc.length > 60
    ? `description's first sentence is ${shortDesc.length} chars; it becomes short_description in agents/openai.yaml, where hosts truncate at ~60. Give the description a terminal period after a standalone opening sentence.`
    : null

  const triggers = /Triggers\s*[-—:]\s*([^.]+)\./i.exec(desc)?.[1]?.trim()

  const chapters = existsSync(refs) ? readdirSync(refs)
    .filter((f) => f.endsWith('.md'))
    .sort()
    .map((file) => {
      const body = readFileSync(join(refs, file), 'utf8')
      const title = (/^#\s+(.+)$/m.exec(body)?.[1] ?? file).trim()
      const zh = /^>\s*\*\*中文速览\*\*[：:]\s*(.+?)$/m.exec(body)?.[1]?.trim()
      const maps = /^\*\*Maps to:\*\*\s*(.+?)$/m.exec(body)?.[1]?.replace(/\[\d+\]/g, '').trim()
      const headings = [...body.matchAll(/^##\s+(.+)$/gm)].map((m) => m[1].trim())
      return {
        path: `references/${file}`,
        title,
        summary_zh: zh ?? null,
        maps_to: maps ?? null,
        headings,
        bytes: Buffer.byteLength(body),
        sha256: sha256(body),
      }
    }) : []

  return { name, dir, fm, desc, shortDesc, triggers, chapters, fatal, displayName: cfg.displayName ?? name }
}

const allLoaded = (named.length ? allSkills : skills).map(readSkill)
const broken = allLoaded.filter((s) => s.fatal)
// A skill that cannot produce a valid adapter is left out of the build and out
// of AGENTS.md, rather than blocking its siblings. It is reported at the end.
const healthy = allLoaded.filter((s) => !s.fatal)
const loaded = healthy.filter((s) => skills.includes(s.name))
// AGENTS.md describes every healthy skill, not only the ones named on the command line.
const loadedAll = healthy

// ---------------------------------------------------------------- artifacts

const outputs = []

for (const s of loaded) {
  outputs.push([join(s.dir, 'index.json'), JSON.stringify({
    $comment: banner(`${s.name}/SKILL.md`),
    name: s.fm.name,
    description: s.fm.description,
    entry: 'SKILL.md',
    spec: 'https://agentskills.io/specification',
    chapters: s.chapters,
  }, null, 2) + '\n'])

  outputs.push([join(s.dir, 'agents', 'openai.yaml'), `# ${banner(`${s.name}/SKILL.md`)}
interface:
  display_name: ${s.displayName}
  short_description: ${JSON.stringify(s.shortDesc)}
policy:
  allow_implicit_invocation: true
`])
}


const agentsMd = `<!-- ${banner('each skill\'s SKILL.md')} -->

# Agent instructions

This repository carries ${loadedAll.length} specification-anchored virtualization
skill${loadedAll.length === 1 ? '' : 's'}. Every architectural claim in them is anchored to a vendor
specification by document number and section, and time-sensitive facts are
quarantined in a single dated file per skill.

${loadedAll.map((s) => `## ${s.displayName} — \`${s.name}/\`

${s.shortDesc}

**Read \`${s.name}/SKILL.md\` before answering anything it covers.**${s.triggers ? `

Triggers: ${s.triggers}.` : ''}

It routes to one chapter under \`${s.name}/references/\` per topic, each mapped to
the specification chapter it covers. Load the chapter you need, not the whole
directory. \`${s.name}/index.json\` is the machine-readable table of contents.
`).join('\n')}${loadedAll.length > 1 ? `
## Choosing between them

Route by whose specification answers the question, not by the words in it. A
question is AMD-primary when the answer is an AMD register, bit, exit code or
instruction — **including when it is phrased in Windows terms** ("my Ryzen and
Hyper-V", "AMD-V greyed out"); it is Intel-primary under the mirror rule.
Symmetric comparisons ("Intel vs AMD", "SEV-SNP vs TDX") are answered by
\`intel-vt/\`, which states the correspondence and defers bit-level AMD detail
to \`amd-virtualization/\`. ARM- and RISC-V-primary questions are answered by
\`intel-vt/\`; neither skill claims non-x86 depth beyond a comparison.
` : ''}`

outputs.push([join(ROOT, 'AGENTS.md'), agentsMd])

// AGENTS.md is merged into an agent's startup instructions, where the budget is
// shared with every other instruction file. Two skills cost ~2 KiB; a ceiling
// well under that budget catches anyone inlining a routing table into it.
const agentsBytes = Buffer.byteLength(agentsMd)
if (agentsBytes > 8192) {
  console.error(`\nAGENTS.md is ${agentsBytes} bytes, over the 8192-byte ceiling.`)
  console.error('It is merged into every agent\'s startup instructions — keep pointers here and content in the chapters.\n')
  process.exit(1)
}

// -------------------------------------------------------------- write/check

let drifted = 0
for (const [path, content] of outputs) {
  const rel = relative(ROOT, path).replace(/\\/g, '/')
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null
  if (current === content) { if (!CHECK) console.log(`  unchanged  ${rel}`); continue }
  if (CHECK) {
    console.error(`  DRIFT      ${rel}${current === null ? ' (missing)' : ''}`)
    drifted++
    continue
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, content)
  console.log(`  ${current === null ? 'created   ' : 'updated   '} ${rel}`)
}

for (const s of broken) console.error(`
  SKIPPED    ${s.name} — ${s.fatal}`)

if (CHECK) {
  if (broken.length) {
    console.error(`
${broken.length} skill(s) cannot be built — fix the above, then run: node tools/build.mjs
`)
    process.exit(1)
  }
  if (drifted) {
    console.error(`\n${drifted} generated file(s) out of date — run: node tools/build.mjs\n`)
    process.exit(1)
  }
  console.log('\ngenerated files are up to date\n')
} else {
  const n = loaded.reduce((a, s) => a + s.chapters.length, 0)
  console.log(`\n${n} chapter(s) indexed across ${loaded.length} skill(s)\n`)
}
